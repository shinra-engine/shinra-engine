//! Turning a source tree into `.wasm`.
//!
//! One `rustc` per module. No `Cargo.toml` per module and no build script: a
//! module is a single file plus whatever it pulls in, and making it a package
//! would add a manifest that could disagree with the tree.
//!
//! # The three flags that are not optional
//!
//! Every one of them fails silently if it is wrong, which is why they live in
//! one function and are documented where they are passed:
//!
//! ```text
//! --import-memory     or the module writes into a memory nobody reads
//! --global-base=N     or two modules' statics land on each other
//! -z stack-size=N     or a module's stack reaches down into the world
//! ```
//!
//! `--global-base` is assigned by *category*, never by load order, so any
//! `game/*.rs` lands on the same addresses as the one it replaces. That is
//! what makes a hot swap a swap rather than a relocation.

use crate::discover::{Category, GameSrc};
use anyhow::{bail, Context, Result};
use se_vm::memory::{Slot, STACK_SIZE};
use std::path::{Path, PathBuf};
use std::process::Command;

/// Where `libse.rlib` lives, built for the target a module is.
///
/// `se-macro` is a proc-macro crate and is always built for the *host*, never
/// for wasm32, so a module's compile needs both dependency paths — the wasm
/// one for `se` itself and the host one for the macro it re-exports. That is
/// the one build-system consequence of using an attribute at all.
pub struct Engine {
    pub root: PathBuf,
    pub se_rlib: PathBuf,
    pub wasm_deps: PathBuf,
    pub host_deps: PathBuf,
}

impl Engine {
    /// `$SHINRA_ENGINE`, else the workspace this binary was built from.
    pub fn find(profile: &str) -> Result<Engine> {
        let root = match std::env::var_os("SHINRA_ENGINE") {
            Some(p) => PathBuf::from(p),
            None => {
                let exe = std::env::current_exe()?;
                exe.ancestors()
                    .find(|a| a.join("crates/se/Cargo.toml").is_file())
                    .map(|a| a.to_path_buf())
                    .context("cannot find the engine; set SHINRA_ENGINE to its checkout")?
            }
        };
        let wasm = root.join("target/wasm32-unknown-unknown").join(profile);
        Ok(Engine {
            se_rlib: wasm.join("libse.rlib"),
            wasm_deps: wasm.join("deps"),
            host_deps: root.join("target").join(profile).join("deps"),
            root,
        })
    }

    /// `se` is what a module's attributes come from, so it has to exist before
    /// the module does.
    pub fn ensure(&self, profile: &str) -> Result<()> {
        let mut c = Command::new("cargo");
        c.arg("build").arg("-p").arg("se");
        c.args(["--target", "wasm32-unknown-unknown"]);
        if profile == "release" {
            c.arg("--release");
        }
        c.arg("--manifest-path").arg(self.root.join("Cargo.toml"));
        let out = c.output().context("running cargo build -p se")?;
        if !out.status.success() {
            bail!("building `se` for wasm32 failed:\n{}", String::from_utf8_lossy(&out.stderr));
        }
        if !self.se_rlib.is_file() {
            bail!("expected {} after building `se`", self.se_rlib.display());
        }
        Ok(())
    }
}

pub struct Built {
    pub contract: PathBuf,
    pub modules: Vec<(String, String, PathBuf)>,
}

/// Which slot a category's modules occupy. `asset` and `render` carry no code
/// on this route, but they are still built into the render slot's region so
/// that a render module which *does* grow code has somewhere to live.
pub fn slot_of(category: &str) -> Slot {
    match category {
        "game" => Slot::Game,
        "process" => Slot::Process,
        _ => Slot::Render,
    }
}

fn abs(p: &Path) -> PathBuf {
    std::fs::canonicalize(p).unwrap_or_else(|_| p.to_path_buf())
}

/// `process/` is additive; every other category is a choice.
///
/// `bundle.rs` had this right before any of it was wasm: *"a category nobody
/// chose from loads everything in it — which is what makes `process/` additive
/// and `render/` a decision."* Under one shared memory it is also forced.
/// Every module with code needs its own region, so N process modules would
/// need N regions; one module holding N stages needs one. The `se.stages`
/// entries concatenate, which is exactly why they carry their own lengths
/// instead of sharing a header.
pub fn is_additive(category: &str) -> bool {
    category == "process"
}

/// The generated crate root for one module.
///
/// It includes `contract.rs` at crate level, so a module reaches `Transform`,
/// `arena::COL_*` and the rest through `use crate::*` — the contract is not
/// something a module imports, it is the crate it is compiled into.
fn root_for(members: &[&str], cat: &Category, contract_rs: &Path, assets: &[String]) -> String {
    let dir = abs(&cat.dir);
    let mut s = String::new();
    s.push_str("// generated by shinra — do not edit\n");
    s.push_str("#![no_std]\n#![allow(dead_code, unused_imports)]\n");
    s.push_str("#[panic_handler]\n");
    s.push_str("fn se_panic(_: &core::panic::PanicInfo) -> ! { core::arch::wasm32::unreachable() }\n");
    s.push_str(&format!("include!({:?});\n", abs(contract_rs)));
    s.push_str(&format!(
        "#[used]\n#[link_section = {:?}]\npub static SE_CONTRACT_ID: [u8; 8] = CONTRACT_ID.to_le_bytes();\n",
        se_contract::table::CONTRACT_ID_SECTION
    ));
    // Reaching a column is one load through the descriptor the host published,
    // never a baked address: that is what lets a column grow or move.
    s.push_str(
        "#[inline]\npub unsafe fn se_col(i: u32) -> Column { *((arena::COLUMNS + i * 16) as *const Column) }\n\
         #[inline]\npub unsafe fn se_pool(i: u32) -> Pool { *((arena::POOLS + i * 8) as *const Pool) }\n\
         #[inline]\npub unsafe fn se_row<T>(c: &Column, i: u32) -> *mut T { (c.base + i * c.stride) as *mut T }\n\
         #[inline]\npub unsafe fn se_blob(s: u32) -> Span { *((arena::BLOBS + s * 8) as *const Span) }\n\
          /// Ask for a roster. The control layer decides how many rows should\n\
          /// exist; the host clamps the answer to the capacity it placed.\n\
          #[inline]\npub unsafe fn se_pool_mut(i: u32) -> *mut Pool { (arena::POOLS + i * 8) as *mut Pool }\n",
    );
    // Assets are named by constant, never by file order.
    s.push_str("pub mod assets {\n");
    for (i, a) in assets.iter().enumerate() {
        s.push_str(&format!("    pub const {}: u32 = {i};\n", a.to_uppercase().replace('-', "_")));
    }
    s.push_str(&format!("    pub const N: u32 = {};\n}}\n", assets.len()));
    s.push_str(&format!("#[path = {dir:?}]\nmod {} {{\n", cat.name));
    for sh in &cat.shared {
        s.push_str(&format!("    pub mod {sh};\n"));
    }
    for m in members {
        s.push_str(&format!("    pub mod {m};\n"));
    }
    s.push_str("}\n");
    s
}

fn run(mut c: Command, what: &str) -> Result<()> {
    let out = c.output().with_context(|| format!("running rustc for {what}"))?;
    if !out.status.success() {
        bail!("{what} failed to build:\n{}", String::from_utf8_lossy(&out.stderr));
    }
    let err = String::from_utf8_lossy(&out.stderr);
    if !err.trim().is_empty() {
        eprint!("{err}");
    }
    Ok(())
}

pub(crate) fn compile(
    name: &str,
    members: &[&str],
    cat: &Category,
    out: &Path,
    gen: &Path,
    contract_rs: &Path,
    engine: &Engine,
    profile: &str,
    assets: &[String],
) -> Result<PathBuf> {
    let root = gen.join(format!("{}_{}_root.rs", cat.name, name));
    std::fs::write(&root, root_for(members, cat, contract_rs, assets))?;
    let cdir = out.join(&cat.name);
    std::fs::create_dir_all(&cdir)?;
    let wasm = cdir.join(format!("{name}.wasm"));
    let slot = slot_of(&cat.name);

    let mut c = Command::new("rustc");
    c.args(["--edition", "2021", "--target", "wasm32-unknown-unknown"]);
    c.args(["--crate-type", "cdylib", "--crate-name", name]);
    // Every module imports the host's memory; none exports one of its own.
    c.arg("-C").arg("link-arg=--import-memory");
    // Statics by category, so a replacement lands where its predecessor was.
    c.arg("-C").arg(format!("link-arg=--global-base={}", slot.global_base()));
    // Uniform across every module, and equal to the contract's arena base.
    c.arg("-C").arg(format!("link-arg=-zstack-size={STACK_SIZE}"));
    c.arg("-C").arg("panic=abort");
    // Both paths: the module is wasm32, the attribute that shapes it is not.
    c.arg("--extern").arg(format!("se={}", engine.se_rlib.display()));
    c.arg("-L").arg(format!("dependency={}", engine.wasm_deps.display()));
    c.arg("-L").arg(format!("dependency={}", engine.host_deps.display()));
    c.arg("-C").arg(if profile == "release" { "opt-level=3" } else { "opt-level=1" });
    c.arg("-o").arg(&wasm).arg(&root);
    run(c, &format!("{}/{name}", cat.name))?;
    Ok(wasm)
}

/// Build the contract, then every module against it.
pub fn build(src: &GameSrc, out: &Path, profile: &str) -> Result<Built> {
    let engine = Engine::find(profile)?;
    engine.ensure(profile)?;
    std::fs::create_dir_all(out)?;
    let gen = out.join(".gen");
    std::fs::create_dir_all(&gen)?;

    // The contract first: nothing else means anything without it, and a change
    // to it is not a reload — it is a different game.
    let g = se_contract::generate(&src.contract)?;
    let contract_rs = out.join("contract.rs");
    std::fs::write(&contract_rs, &g.rust)?;
    std::fs::write(out.join("contract.wgsl"), &g.wgsl)?;
    let contract_wasm = out.join("contract.wasm");
    std::fs::write(&contract_wasm, &g.module)?;

    let assets = src.asset_ids();
    let mut modules = Vec::new();
    for cat in &src.categories {
        if cat.modules.is_empty() {
            continue;
        }
        if is_additive(&cat.name) {
            // Every stage in one module, sharing one region and one section.
            let members: Vec<&str> = cat.modules.iter().map(|m| m.name.as_str()).collect();
            let wasm = compile(&cat.name, &members, cat, out, &gen, &contract_rs, &engine, profile, &assets)?;
            modules.push((cat.name.clone(), cat.name.clone(), wasm));
        } else {
            for m in &cat.modules {
                let wasm =
                    compile(&m.name, &[m.name.as_str()], cat, out, &gen, &contract_rs, &engine, profile, &assets)?;
                modules.push((cat.name.clone(), m.name.clone(), wasm));
            }
        }
    }
    Ok(Built { contract: contract_wasm, modules })
}
